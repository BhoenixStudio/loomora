import type { Control, ComponentMeta, RelatedConfig, SpecificProp } from './types'

/** Controls every Loomora form field shares (label, helper text, error, state flags). */
function fieldControls(defaults: { label: string }): Control[] {
  return [
    { kind: 'text', key: 'label', label: 'label', default: defaults.label },
    { kind: 'text', key: 'inputHelper', label: 'inputHelper', default: '', placeholder: 'Helper text under the field' },
    { kind: 'text', key: 'error', label: 'errors (message)', default: '', placeholder: 'Shows an error when set' },
    { kind: 'toggle', key: 'required', label: 'properties.required', default: false },
    { kind: 'toggle', key: 'disabled', label: 'properties.disabled', default: false },
    { kind: 'toggle', key: 'loading', label: 'loading', default: false },
    { kind: 'toggle', key: 'active', label: 'active', default: false, hint: 'Forces the floating label up.' },
  ]
}

